def airframe_hash(params: AircraftParameters) -> str:
    """A short digest of the parameters an airframe file was generated from.

    The adapter regenerates a file whose digest no longer matches, so editing
    ``AircraftParameters`` can never leave a stale airframe on disk flying a
    platform the rest of the system has stopped describing.
    """
    payload = repr(sorted(asdict(params).items())).encode()
    return hashlib.sha256(payload).hexdigest()[:16]


def write_data_root(root: Path, airframes: dict[str, AircraftParameters]) -> list[Path]:
    """Write a JSBSim data root containing only these fictional airframes.

    Returns the files written or refreshed. A file whose digest already matches
    is left alone, so repeated starts do not rewrite it.
    """
    written: list[Path] = []
    for name, params in sorted(airframes.items()):
        directory = root / "aircraft" / name
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"{name}.xml"
        stamp = directory / f"{name}.sha256"
        digest = airframe_hash(params)

        if path.exists() and stamp.exists() and stamp.read_text().strip() == digest:
            continue

        path.write_text(airframe_xml(params), encoding="utf-8")
        stamp.write_text(digest, encoding="utf-8")
        written.append(path)
    return written
