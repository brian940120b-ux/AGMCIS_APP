"""Writing a fictional airframe out as JSBSim XML (PHASE 16).

JSBSim ships with real aircraft definitions. **None of them are used here.** The
platform's rule is that every entity, airframe and parameter is fictional, and
loading a bundled model would break it on the first tick. So the adapter points
JSBSim at a data root that this module generates, containing exactly one
aircraft: the same invented airframe ``simulation/aircraft.py`` already
describes.

Generating rather than hand-writing the XML is what keeps the two physics
backends honest about each other. ``Simple6DOFModel`` and JSBSim read the *same*
``AircraftParameters`` — mass, inertia, reference geometry, every aerodynamic
coefficient — so a difference between the two is a difference between the
*models*, never between two airframes that drifted apart in separate files.

Two deliberate choices:

**Thrust is an external force, not an engine.** JSBSim's engine types each carry
their own spool-up, fuel flow and altitude lapse. Our fictional platform's
thrust model is ``max_thrust_n * throttle`` along body X, and an external
reaction reproduces exactly that. Inventing a turbine to wrap it would add
fiction that the other backend does not have.

**Lift and drag are tables.** ``Cl`` saturates at ``cl_max`` to model stall, and
JSBSim has no clamp inside a product. A table on angle of attack expresses the
saturation directly and is the idiomatic form. ``Cd = cd_0 + k*Cl^2`` is
tabulated from the same clamped ``Cl``, so the two stay consistent by
construction.

Everything emitted here is invented for simulation research. It models flight
and nothing else: there is no weapon, store, targeting or engagement modelling
in any of it.
"""

from __future__ import annotations

import hashlib
import math
from dataclasses import asdict
from pathlib import Path

from simulation.aircraft import AircraftParameters

# JSBSim works internally in imperial units, and an external force is declared
# in pounds. One pound-force in newtons, exactly as defined.
NEWTONS_PER_LBF = 4.4482216152605

# Angle-of-attack breakpoints for the lift and drag tables, in degrees. The
# range runs well past stall so a mishandled aircraft still gets a defined
# coefficient rather than an extrapolation off the end of the table.
_ALPHA_MIN_DEG = -30.0
_ALPHA_MAX_DEG = 30.0
_ALPHA_STEP_DEG = 1.0


def _alpha_breakpoints() -> list[float]:
    count = round((_ALPHA_MAX_DEG - _ALPHA_MIN_DEG) / _ALPHA_STEP_DEG) + 1
    return [_ALPHA_MIN_DEG + i * _ALPHA_STEP_DEG for i in range(count)]


def lift_coefficient(params: AircraftParameters, alpha_rad: float) -> float:
    """``Cl`` at an angle of attack, clamped at the stall ceiling.

    The same expression ``Simple6DOFModel`` evaluates analytically.
    """
    cl = params.cl_0 + params.cl_alpha * alpha_rad
    return max(-params.cl_max, min(params.cl_max, cl))


def drag_coefficient(params: AircraftParameters, alpha_rad: float) -> float:
    """``Cd = cd_0 + k * Cl^2``, from the clamped ``Cl``."""
    cl = lift_coefficient(params, alpha_rad)
    return params.cd_0 + params.induced_drag_k * cl * cl


def _table(rows: list[tuple[float, float]]) -> str:
    body = "\n".join(f"        {a:.6f}  {v:.6f}" for a, v in rows)
    return (
        "     <table>\n"
        '      <independentVar lookup="row">aero/alpha-deg</independentVar>\n'
        "      <tableData>\n"
        f"{body}\n"
        "      </tableData>\n"
        "     </table>"
    )


def airframe_xml(params: AircraftParameters) -> str:
    """The JSBSim aircraft definition for one fictional platform."""
    alphas = _alpha_breakpoints()
    lift_rows = [(a, lift_coefficient(params, math.radians(a))) for a in alphas]
    drag_rows = [(a, drag_coefficient(params, math.radians(a))) for a in alphas]

